/**
 * Função utilitária para buscar veículo na base
 */
export function findVehicleSpecs(make: string, model: string, year?: number): VehicleSpec | undefined {
  const normMake = make.trim().toLowerCase();
  const normModel = model.trim().toLowerCase();

  // 1. Busca exata por make e model
  const match = POPULAR_VEHICLES_DATABASE.find(v => {
    const vMake = v.make.toLowerCase();
    const vModel = v.model.toLowerCase();
    const matchesMake = vMake === normMake || normModel.includes(vMake);
    const matchesModel = vModel.includes(normModel) || normModel.includes(vModel.split(' ')[0].toLowerCase());
    const matchesYear = year ? v.years.includes(year) : true;
    return matchesMake && matchesModel && matchesYear;
  });

  if (match) return match;

  // 2. Busca aproximada por palavras-chave no modelo
  return POPULAR_VEHICLES_DATABASE.find(v => {
    const searchTerms = normModel.split(/[\s-]+/).filter(t => t.length > 2);
    const vFull = `${v.make} ${v.model}`.toLowerCase();
    return searchTerms.some(term => vFull.includes(term));
  });
}

/**
 * Retorna lista de montadoras disponíveis
 */
export function getAvailableMakes(): string[] {
  const makes = new Set(POPULAR_VEHICLES_DATABASE.map(v => v.make));
  return Array.from(makes).sort();
}

/**
 * Retorna modelos de uma montadora específica
 */
export function getModelsByMake(make: string): VehicleSpec[] {
  return POPULAR_VEHICLES_DATABASE.filter(
    v => v.make.toLowerCase() === make.trim().toLowerCase()
  );
}

/**
 * Calcula autonomias padrão com tanque cheio baseado na especificação
 */
export function calcVehicleAutonomies(spec: VehicleSpec) {
  const isElectric = spec.fuelType === 'Elétrico';
  
  if (isElectric) {
    return {
      isElectric: true,
      cityAutonomyGas: 0,
      highwayAutonomyGas: 0,
      cityAutonomyEth: 0,
      highwayAutonomyEth: 0,
      electricRangeKm: spec.avgConsumption,
      batteryKwh: spec.tankCapacity,
      costPerKmElectric: 0.08, // Média Brasil residencial
    };
  }

  const cityGasKm = Math.round(spec.tankCapacity * spec.cityConsumptionGas);
  const highwayGasKm = Math.round(spec.tankCapacity * spec.highwayConsumptionGas);
  const cityEthKm = Math.round(spec.tankCapacity * spec.cityConsumptionEth);
  const highwayEthKm = Math.round(spec.tankCapacity * spec.highwayConsumptionEth);

  return {
    isElectric: false,
    cityAutonomyGas: cityGasKm,
    highwayAutonomyGas: highwayGasKm,
    cityAutonomyEth: cityEthKm,
    highwayAutonomyEth: highwayEthKm,
    tankLiters: spec.tankCapacity,
    trunkLiters: spec.trunkCapacity,
    bestCityFuel: spec.cityConsumptionEth > 0 ? 'Etanol (se paridade < 70%)' : 'Gasolina',
  };
}
